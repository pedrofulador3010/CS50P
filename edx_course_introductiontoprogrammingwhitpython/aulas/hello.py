def main():
    # Lê o nome, remover os espaços e capitalizar o nome
    name = str(input('What is your name? ')).strip().capitalize()
    # Escreve um hello com o nome de entrada
    print(f'Hello, {name}!') 


main() 
# Coisas que recebem entradas e produzem uma saída são chamadas funções. Isto é, as funções são aquelas coisas que recebem uma entrada e produzem uma saída.